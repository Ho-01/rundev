const root = document.documentElement;
const localeButton = document.querySelector(".locale-button");
const localeCurrent = document.querySelector(".locale-current");
const localeNext = document.querySelector(".locale-next");
const themeButton = document.querySelector(".theme-button");
const themeMeta = document.querySelector('meta[name="theme-color"]');
const menuButton = document.querySelector(".mobile-menu-button");
const nav = document.querySelector(".site-nav");

let locale = localStorage.getItem("rundev-site-locale") || (navigator.language.toLowerCase().startsWith("ko") ? "ko" : "en");
let theme = localStorage.getItem("rundev-site-theme") || (window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");

function applyLocale(nextLocale) {
  locale = nextLocale;
  const dictionary = copy[locale];
  root.lang = locale;
  document.title = dictionary.metaTitle;
  document.querySelector('meta[name="description"]').setAttribute("content", dictionary.metaDescription);
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = dictionary[node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const value = dictionary[node.dataset.i18nHtml];
    if (value) node.innerHTML = value;
  });
  localeCurrent.textContent = locale.toUpperCase();
  localeNext.textContent = locale === "ko" ? "EN" : "KO";
  localeButton.setAttribute("aria-label", locale === "ko" ? "Switch language to English" : "언어를 한국어로 전환");
  menuButton.querySelector(".sr-only").textContent = nav.classList.contains("is-open") ? dictionary.closeMenu : dictionary.openMenu;
  updateThemeLabel();
  localStorage.setItem("rundev-site-locale", locale);
}

function applyTheme(nextTheme) {
  theme = nextTheme;
  root.dataset.theme = theme;
  themeMeta.setAttribute("content", theme === "dark" ? "#151614" : "#f4f2eb");
  localStorage.setItem("rundev-site-theme", theme);
  updateThemeLabel();
}

function updateThemeLabel() {
  const dictionary = copy[locale];
  themeButton.setAttribute("aria-label", theme === "dark" ? dictionary.lightMode : dictionary.darkMode);
}

localeButton.addEventListener("click", () => applyLocale(locale === "ko" ? "en" : "ko"));
themeButton.addEventListener("click", () => applyTheme(theme === "dark" ? "light" : "dark"));

menuButton.addEventListener("click", () => {
  const open = nav.classList.toggle("is-open");
  menuButton.setAttribute("aria-expanded", String(open));
  menuButton.querySelector(".sr-only").textContent = open ? copy[locale].closeMenu : copy[locale].openMenu;
});

nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("is-open");
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.querySelector(".sr-only").textContent = copy[locale].openMenu;
}));

const featureTabs = [...document.querySelectorAll("[data-feature]")];
const featurePanels = [...document.querySelectorAll("[data-feature-panel]")];

function selectFeature(name, focus = false) {
  featureTabs.forEach((tab) => {
    const selected = tab.dataset.feature === name;
    tab.setAttribute("aria-selected", String(selected));
    tab.tabIndex = selected ? 0 : -1;
    if (selected && focus) tab.focus();
  });
  featurePanels.forEach((panel) => {
    const selected = panel.dataset.featurePanel === name;
    panel.hidden = !selected;
    panel.classList.toggle("is-active", selected);
  });
}

featureTabs.forEach((tab, index) => {
  tab.addEventListener("click", () => selectFeature(tab.dataset.feature));
  tab.addEventListener("keydown", (event) => {
    if (!['ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown'].includes(event.key)) return;
    event.preventDefault();
    const offset = ['ArrowRight', 'ArrowDown'].includes(event.key) ? 1 : -1;
    const next = (index + offset + featureTabs.length) % featureTabs.length;
    selectFeature(featureTabs[next].dataset.feature, true);
  });
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    entry.target.classList.add("is-visible");
    observer.unobserve(entry.target);
  });
}, { threshold: 0.12 });

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

applyTheme(theme);
applyLocale(locale);
selectFeature("progress");
